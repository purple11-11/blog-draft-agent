def build_posting_instruction(state: State, extra_requirements: str = "") -> str:
    """write_posting과 write_posting_campaign이 함께 쓰는 지침 조립 함수."""
    meta = state["meta"]

    store_info = {k: v for k, v in meta.items()
                  if k not in ("keyword", "title", "campaign_template", "name", "post_type")}

    sections_text = "\n\n".join([
        f"[매장정보]\n{json.dumps(store_info, ensure_ascii=False)}",
        f"[매장분위기]\n{describe_section(PHOTO_ROOT / '3_매장분위기')}",
        f"[메뉴]\n{describe_menu(PHOTO_ROOT / '4_메뉴')}",
    ])

    instruction = (
        f"아래 정보로 네이버 블로그 글 본문을 쓴다. 제목은 '{meta.get('title', '')}'이다.\n"
        "아래 템플릿의 헤딩과 '✔'·'📍' 같은 라벨은 그대로 쓰고 <> 안만 채운다. "
        "템플릿에 없는 문장·섹션, '지도' 관련 내용, '비추천' 목록은 추가하지 않는다.\n\n"
        f"=== 템플릿 ===\n{TEMPLATE_SKELETON}\n\n"
        "메뉴 항목은 '이번 글 재료'의 요리명·가격 정보만 그대로 쓴다.\n"
        "주소·전화·영업시간·주차·방문 시기 자리는 '이번 글 재료'의 [매장정보]에 있는 값을 그대로 채운다. "
        "값이 없는 항목만 빈칸으로 둔다.\n"
        "'이번 글 재료'의 사진 설명은 완성된 문장이 아니라 짧은 사실 나열이다. "
        "이 사실들을 그대로 잇지 말고, 그걸 재료로 삼아 본인이 직접 겪은 것처럼 새 문장을 써라. "
        "여기는 맛집 후기이지 인테리어 소개 글이 아니다. '매장 분위기'는 사진이 몇 장이든 "
        "전체를 종합해 3~4문장으로만 요약한다. 메뉴 섹션보다 짧아야 한다. "
        "재료에 보이는 사물을 전부 나열하지 말고, 인상적인 것 한두 개만 골라 "
        "그것에 대한 본인의 반응(좋았다/신기했다/편했다 등)을 붙여 후기답게 쓴다.\n"
        f"{STYLE_RULES}"
        f"{extra_requirements}\n\n"
        f"=== 이번 글 재료 ===\n{sections_text}"
    )

    if state["feedback"]:
        instruction += f"\n\n=== 지난 지적 (반드시 반영해서 다시 쓴다) ===\n{state['feedback']}"

    return instruction
